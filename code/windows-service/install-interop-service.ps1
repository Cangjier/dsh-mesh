param(
  [string]$Root = '',
  [string]$ServiceName = 'DSH-Interop',
  [string]$DshHome = '',
  [int]$Port = 8765,
  [string]$Bind = '127.0.0.1',
  [string]$Token = '',
  [string]$Model = 'deepseek-flash',
  [switch]$Approve,
  [switch]$UseGatePassword
)

$ErrorActionPreference = 'Stop'
if ([string]::IsNullOrWhiteSpace($Root)) {
  $Root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
}
$Root = (Resolve-Path $Root).Path
if ([string]::IsNullOrWhiteSpace($DshHome)) {
  $DshHome = Join-Path $Root 'home'
}
if ($UseGatePassword) {
  $gateEnv = Join-Path $Root 'config\gate.env'
  $gateLine = Get-Content -LiteralPath $gateEnv -ErrorAction Stop | Where-Object { $_ -match '^DSH_GATE_PASSWORD=' } | Select-Object -First 1
  if ([string]::IsNullOrWhiteSpace($gateLine)) { throw 'gate.env has no DSH_GATE_PASSWORD' }
  $Token = $gateLine.Substring('DSH_GATE_PASSWORD='.Length).Trim()
  if ([string]::IsNullOrWhiteSpace($Token)) { throw 'DSH_GATE_PASSWORD is empty' }
}
if ([string]::IsNullOrWhiteSpace($Token)) {
  $Token = -join ((48..57) + (65..90) + (97..122) | Get-Random -Count 64 | ForEach-Object { [char]$_ })
}
$envFile = Join-Path $Root 'config\interop.env'
$lines = @(
  '# Generated by install-interop-service.ps1',
  "DSH_HOME=$DshHome",
  "DSH_INTEROP_BIND=$Bind",
  "DSH_INTEROP_PORT=$Port",
  "DSH_INTEROP_TOKEN=$Token",
  'DSH_INTEROP_PROVIDER=deepseek-official',
  "DSH_INTEROP_MODEL=$Model",
  "DSH_INTEROP_APPROVE=$(if ($Approve) { '1' } else { '0' })",
  "DSH_INTEROP_USE_GATE_PASSWORD=$(if ($UseGatePassword) { '1' } else { '0' })"
)
[System.IO.File]::WriteAllText($envFile, ($lines -join "`r`n") + "`r`n", [System.Text.UTF8Encoding]::new($false))
New-Item -ItemType Directory -Force -Path (Join-Path $Root 'data') | Out-Null
[System.IO.File]::WriteAllText((Join-Path $Root 'data\interop-token'), "$Token`r`n", [System.Text.UTF8Encoding]::new($false))

$source = Join-Path $PSScriptRoot 'DshInteropService.cs'
$exe = Join-Path $Root 'dsh-interop-service.exe'
$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
if (-not (Test-Path $csc)) { $csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework\v4.0.30319\csc.exe' }
if (-not (Test-Path $csc)) { throw 'Cannot find the .NET Framework C# compiler (csc.exe).' }

$existing = Get-Service -Name $ServiceName -ErrorAction SilentlyContinue
if ($existing) {
  Write-Host "Removing existing service $ServiceName"
  Stop-Service -Name $ServiceName -Force -ErrorAction SilentlyContinue
  & sc.exe delete $ServiceName 2>$null | Out-Null
  Start-Sleep -Seconds 2
}

Write-Host "Compiling $exe"
& $csc /nologo /target:exe /out:$exe /r:System.ServiceProcess.dll $source
if ($LASTEXITCODE -ne 0) { throw "csc failed with exit code $LASTEXITCODE" }

$binPath = '"' + $exe + '"'
& sc.exe create $ServiceName binPath= $binPath start= auto DisplayName= 'DSH Interop HTTP' | Out-Null
if ($LASTEXITCODE -ne 0) { throw "sc create failed with exit code $LASTEXITCODE" }
& sc.exe description $ServiceName 'Independent DSH interaction HTTP service (session create/wait/notify)' | Out-Null
& sc.exe failure $ServiceName reset= 86400 actions= restart/5000/restart/10000/restart/30000 | Out-Null
& sc.exe start $ServiceName | Out-Null
if ($LASTEXITCODE -ne 0) { throw "sc start failed with exit code $LASTEXITCODE" }

$deadline = (Get-Date).AddSeconds(90)
$healthy = $false
while ((Get-Date) -lt $deadline) {
  try {
    $health = Invoke-WebRequest -Uri "http://127.0.0.1:$Port/healthz" -UseBasicParsing -TimeoutSec 3
    if ($health.StatusCode -eq 200) {
      $state = $health.Content | ConvertFrom-Json
      if ($state.sdk -eq 'ready') { Write-Host $health.Content; $healthy = $true; break }
    }
  } catch { }
  Start-Sleep -Seconds 2
}
Get-Service -Name $ServiceName | Select-Object Name, Status, StartType
Write-Host "Token file: $Root\data\interop-token (or DSH_INTEROP_TOKEN in config\interop.env)"
if (-not $healthy) {
  Get-Content (Join-Path $Root 'data\interop-service.log') -Tail 60 -ErrorAction SilentlyContinue
  throw 'Interop service did not become healthy.'
}
Write-Host "Interop service is running on http://$Bind`:$Port"
