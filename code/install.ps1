param(
  [int]$Port = 8080,
  [string]$Bind = '0.0.0.0',
  [string]$Password = '',
  [string]$ClusterKey = '',
  [string]$TrustedHosts = '',
  [switch]$InstallTask,
  [switch]$InstallService
)

$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$ConfigDir = Join-Path $Root 'config'
$DataDir = Join-Path $Root 'data'
$Workspace = Join-Path $Root 'workspace'
$EnvFile = Join-Path $ConfigDir 'gate.env'

New-Item -ItemType Directory -Force -Path $ConfigDir, $DataDir, $Workspace | Out-Null

function New-Secret([int]$Length) {
  $alphabet = 'abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789'
  $chars = 1..$Length | ForEach-Object { $alphabet[(Get-Random -Maximum $alphabet.Length)] }
  -join $chars
}

if (-not (Test-Path $EnvFile)) {
  if ([string]::IsNullOrWhiteSpace($Password)) { $Password = New-Secret 24 }
  if ([string]::IsNullOrWhiteSpace($ClusterKey)) { $ClusterKey = New-Secret 48 }
  $lines = @(
    '# DeepSeek Harness Web gateway (generated by install.ps1)',
    "# Change the password and restart the task after editing.",
    "DSH_GATE_PORT=$Port",
    "DSH_GATE_BIND=$Bind",
    "DSH_GATE_PASSWORD=$Password",
    'DSH_GATE_COOKIE_DAYS=30',
    "DSH_WORKDIR=$Workspace",
    'DSH_WEB_PORT=31280',
    "DSH_GATE_MEMBER_PORT=$Port",
    "DSH_GATE_CLUSTER_KEY=$ClusterKey",
    "DSH_TRUSTED_HOSTS=$TrustedHosts"
  )
  [System.IO.File]::WriteAllText($EnvFile, ($lines -join "`r`n") + "`r`n", [System.Text.UTF8Encoding]::new($false))
  Write-Host "Wrote $EnvFile"
  Write-Host "Password: $Password"
  Write-Host "Cluster key: $ClusterKey"
} else {
  Write-Host "Keeping $EnvFile"
}

# Win32 firewall; needs elevation. A failure is a warning, not a broken install.
try {
  $ruleName = "DSH Person Web $Port"
  if (-not (Get-NetFirewallRule -DisplayName $ruleName -ErrorAction SilentlyContinue)) {
    New-NetFirewallRule -DisplayName $ruleName -Direction Inbound -Protocol TCP -LocalPort $Port -Action Allow | Out-Null
    Write-Host "Firewall rule added for TCP $Port"
  }
} catch {
  Write-Warning "Could not add the firewall rule (run PowerShell as administrator): $($_.Exception.Message)"
}

if ($InstallTask) {
  try {
    $action = New-ScheduledTaskAction -Execute 'powershell.exe' -Argument "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$Root\start.ps1`""
    $trigger = New-ScheduledTaskTrigger -AtLogOn
    $principal = New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\$env:USERNAME" -LogonType Interactive -RunLevel Highest
    Register-ScheduledTask -TaskName 'DSH Person Web' -Action $action -Trigger $trigger -Principal $principal -Force | Out-Null
    Write-Host "Scheduled task 'DSH Person Web' registered (starts at logon)."
  } catch {
    Write-Warning "Could not register the scheduled task: $($_.Exception.Message)"
  }
}

if ($InstallService) {
  $serviceInstaller = Join-Path $Root 'code\windows-service\install-service.ps1'
  if (-not (Test-Path $serviceInstaller)) {
    Write-Warning "Service installer not found: $serviceInstaller"
  } else {
    & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $serviceInstaller -Root $Root
    if ($LASTEXITCODE -ne 0) { throw "Service installation failed with exit code $LASTEXITCODE" }
    $splitInstaller = Join-Path $Root 'code\windows-service\install-split-services.ps1'
    if (Test-Path $splitInstaller) {
      & powershell.exe -NoProfile -ExecutionPolicy Bypass -File $splitInstaller -Root $Root
      if ($LASTEXITCODE -ne 0) { throw "Split service installation failed with exit code $LASTEXITCODE" }
    }
  }
}

Write-Host ""
Write-Host "Start: powershell -ExecutionPolicy Bypass -File `"$Root\start.ps1`""
Write-Host "Stop:  powershell -ExecutionPolicy Bypass -File `"$Root\stop.ps1`""
Write-Host "Open:  http://<this-host>:$Port/  then enter the password from $EnvFile"
